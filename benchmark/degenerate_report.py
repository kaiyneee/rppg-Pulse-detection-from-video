fin = lambda v: v not in ("", "nan", "-inf", "inf")
def num(v, spec=".3f"):
    if v in ("", "nan"): return "—"
    if v in ("-inf", "inf"): return v
    return format(float(v), spec)

# --- таблица сводки ---
cols = [("condition","условие"),("n_windows","окон"),("publish_rate_gated","publish_gated"),
        ("publish_rate_weighted_only","publish_weighted"),("median_sqi_composite","SQI"),
        ("median_sqi_snr","sqi_snr"),("median_snr_db","snr, дБ"),("median_sqi_roi_agreement","ROI"),
        ("median_sqi_landmark_stability","landmark"),("median_sqi_temporal_consistency","времен."),
        ("flicker_flag_rate","flicker"),("harmonic_plausibility_fail_rate","harm_fail"),
        ("share_published_near_injected","near_inj"),("mae_vs_reference","MAE"),("coverage","покрытие")]
head = "| " + " | ".join(h for _, h in cols) + " |"
sep  = "|" + "|".join("---" for _ in cols) + "|"
body = []
for r in summary:
    cells = [r["condition"], r["n_windows"]] + [num(r[k]) for k, _ in cols[2:]]
    body.append("| " + " | ".join(cells) + " |")

# --- детектор мерцания ---
flick = []
for cond in ("G0","A1","A2","B1w","B1f","B2f","B3","B4","C1","C2","D1"):
    rs = [r for r in rows if r["condition"] == cond]
    reached = [r for r in rs if fin(r["flicker_score"])]
    flags = [r for r in rs if r["flicker_flag"] == "1"]
    med = f"{np.median([float(r['flicker_score']) for r in reached]):.2f}" if reached else "—"
    where = ", ".join(f"{k} ({v})" for k, v in Counter(r["record_id"] for r in flags).most_common(3)) if flags else "—"
    flick.append(f"| `{cond}` | {len(reached)} ({len(reached)/len(rs):.1%}) | {len(flags)} | {med} | {where} |")

a1 = [r for r in rows if r["condition"] == "A1"]
a1_pub = [r for r in a1 if r["published_gated"] == "1"]
a1_idx = Counter(int(r["window_idx"]) for r in a1_pub)
a1_inf = sum(1 for r in a1 if r["snr_db"] == "-inf")

