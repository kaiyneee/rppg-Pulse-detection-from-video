ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "accuracy"


def c(x: float, spec: str = ".3f") -> str:
    return format(x, spec).replace(".", ",")


def main() -> None:
    s = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))

    def row(part: str, label: str) -> str:
        v = s[part]
        b, n = v["baseline"], v["new"]
        return (f"| {label} ({v['n']}) | {c(b['mae_full'])} → **{c(n['mae_full'])}** | "
                f"{c(b['mae'])} → **{c(n['mae'])}** | "
                f"{c(b['outlier_full'] * 100, '.2f')} % → {c(n['outlier_full'] * 100, '.2f')} % | "
                f"{c(b['coverage'] * 100, '.1f')} % → {c(n['coverage'] * 100, '.1f')} % |")

    def paired(part: str) -> str:
        v = s[part]
        return (f"| {part} | {v['better_full']} / {v['worse_full']} из {v['n']} (p = {v['p_full']:.1e}) | "
                f"{v['better_own']} / {v['worse_own']} из {v['n']} (p = {v['p_own']:.1e}) |")

